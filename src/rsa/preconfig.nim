const StartMarker* = "# Generated by RedstoneServerAssembler"

proc boolStr(value: bool): string =
  if value: "true" else: "false"

proc properties*(cfg: ServerConfig): seq[(string, string)] =
  result.add(("server-port", $cfg.serverPort))
  if cfg.serverIp.len > 0:
    result.add(("server-ip", cfg.serverIp))
  result.add(("max-players", $cfg.maxPlayers))
  result.add(("motd", cfg.motd))
  result.add(("online-mode", boolStr(cfg.onlineMode)))
  result.add(("white-list", boolStr(cfg.whiteList)))
  result.add(("gamemode", $cfg.gamemode))
  result.add(("difficulty", $cfg.difficulty))
  result.add(("level-name", cfg.levelName))
  if cfg.levelType.len > 0:
    result.add(("level-type", cfg.levelType))
  result.add(("view-distance", $cfg.viewDistance))
  result.add(("simulation-distance", $cfg.simulationDistance))
  result.add(("spawn-protection", $cfg.spawnProtection))
  result.add(("op-permission-level", $cfg.opPermissionLevel))
  result.add(("generate-structures", boolStr(cfg.generateStructures)))
  result.add(("allow-flight", boolStr(cfg.allowFlight)))

proc setProperty(lines: var seq[string], key, value: string) =
  for i in 0 ..< lines.len:
    let line = lines[i].strip()
    if line.len == 0 or line[0] in {'#', '!'}:
      continue
    let separator = line.find({'=', ':'})
    let current = if separator >= 0: line[0 ..< separator].strip() else: line
    if current == key:
      lines[i] = key & "=" & value
      return
  lines.add(key & "=" & value)

proc writeServerProperties*(dir: string, cfg: ServerConfig) =
  let path = dir / "server.properties"
  var lines =
    if fileExists(path):
      readFile(path).splitLines()
    else:
      @["# Minecraft server properties", "# Generated by RedstoneServerAssembler"]
  for (key, value) in cfg.properties():
    lines.setProperty(key, value)
  writeFile(path, lines.join("\n") & "\n")
  success("Wrote " & path)

proc writeEula*(dir: string) =
  ## Accepts the Minecraft EULA, as stated by the program's banner.
  let path = dir / "eula.txt"
  var lines =
    if fileExists(path):
      readFile(path).splitLines()
    else:
      @["# By changing the setting below to TRUE you are indicating your agreement to our EULA (" & EulaUrl & ")."]
  lines.setProperty("eula", "true")
  writeFile(path, lines.join("\n") & "\n")
  success("Agreement with the EULA")

proc writeStartScript*(dir, launch: string): bool =
  ## Writes start.sh unless a foreign script is already present.
  if launch.len == 0:
    return false
  let path = dir / "start.sh"
  if fileExists(path) and StartMarker notin readFile(path):
    hint("start.sh already exists and was left untouched")
    return false
  writeFile(path, "#!/usr/bin/env sh\n" & StartMarker & "\ncd \"$(dirname \"$0\")\"\nexec " & launch & "\n")
  setFilePermissions(path, {
    fpUserRead, fpUserWrite, fpUserExec,
    fpGroupRead, fpGroupExec, fpOthersRead, fpOthersExec
  })
  success("Created " & path)
  result = true